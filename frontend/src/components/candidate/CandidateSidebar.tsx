interface CandidateSidebarProps {
  onNavigate?: () => void;
}

export default function CandidateSidebar({ onNavigate }: CandidateSidebarProps) {
  const location = useLocation();
  const navigate = useNavigate();
  const { user } = useAuth();

  const handleNav = (href: string) => {
    navigate(href);
    onNavigate?.();
  };

  const isActive = (href: string) => location.pathname === href;

  return (
    <>
      <SidebarNavGroup>
        {mainNavItems.map((item) => (
          <SidebarNavItem
            key={item.href}
            icon={item.icon}
            label={item.label}
            active={isActive(item.href)}
            onClick={() => handleNav(item.href)}
          />
        ))}
      </SidebarNavGroup>
      <SidebarNavGroup label="Career Tools">
        {secondaryNavItems.map((item) => (
          <SidebarNavItem
            key={item.href}
            icon={item.icon}
            label={item.label}
            active={isActive(item.href)}
            onClick={() => handleNav(item.href)}
          />
        ))}
      </SidebarNavGroup>
      <SidebarNavGroup label="Settings">
        {settingsNavItems.map((item) => (
          <SidebarNavItem
            key={item.href}
            icon={item.icon}
            label={item.label}
            active={isActive(item.href)}
            onClick={() => handleNav(item.href)}
          />
        ))}
      </SidebarNavGroup>
      <SidebarFooter>
        <div className="flex items-center gap-3">
          <Avatar size="sm" initials={user?.fullName?.split(' ').map((n: string) => n[0]).join('').toUpperCase() || 'U'} color="primary" />
          <div className="min-w-0 flex-1 hidden lg:block">
            <p className="text-sm font-medium text-neutral-900 truncate">{user?.fullName || 'User'}</p>
            <p className="text-xs text-neutral-500 truncate">{user?.email || ''}</p>
          </div>
        </div>
      </SidebarFooter>
    </>
  );
}
